// ============================================================================
// STRUCTURED PARSING — turns the hand-authored HTML blobs above into ordered
// blocks a component can render with its own design (headings/paragraphs get
// icons, list items become icon + label/value cards) instead of dumping raw
// HTML via dangerouslySetInnerHTML.
// ============================================================================

export type VanSeoBlockType = "h2" | "h3" | "p" | "list";

export interface VanSeoListItem {
  label?: string;
  value: string;
}

export interface VanSeoBlock {
  type: VanSeoBlockType;
  text?: string;
  items?: VanSeoListItem[];
}

function stripTags(text: string): string {
  return text.replace(/<[^>]+>/g, "").trim();
}

function parseVanSeoHtml(html: string): VanSeoBlock[] {
  const blocks: VanSeoBlock[] = [];
  const tagRegex = /<(h2|h3|p|ul)>([\s\S]*?)<\/\1>/g;
  let match: RegExpExecArray | null;

  while ((match = tagRegex.exec(html))) {
    const [, tag, inner] = match;

    if (tag === "ul") {
      const items: VanSeoListItem[] = [];
      const liRegex = /<li>([\s\S]*?)<\/li>/g;
      let liMatch: RegExpExecArray | null;

      while ((liMatch = liRegex.exec(inner))) {
        const liContent = liMatch[1].trim();
        const strongMatch = liContent.match(
          /<strong>(.*?)<\/strong>\s*(.*)/s,
        );

        if (strongMatch) {
          items.push({
            label: stripTags(strongMatch[1]).replace(/:\s*$/, ""),
            value: stripTags(strongMatch[2]),
          });
        } else {
          items.push({ value: stripTags(liContent) });
        }
      }

      blocks.push({ type: "list", items });
    } else {
      blocks.push({ type: tag as VanSeoBlockType, text: stripTags(inner) });
    }
  }

  return blocks;
}

const parsedSeoCache = new Map<string, VanSeoBlock[]>();

/**
 * Returns the structured SEO content for a van by exact category name,
 * or null if no hand-authored entry exists for it.
 */
export function getVanSeoContent(name: string): VanSeoBlock[] | null {
  const html = VAN_DETAIL_SEO_HTML[name];
  if (!html) return null;

  const cached = parsedSeoCache.get(name);
  if (cached) return cached;

  const blocks = parseVanSeoHtml(html);
  parsedSeoCache.set(name, blocks);
  return blocks;
}